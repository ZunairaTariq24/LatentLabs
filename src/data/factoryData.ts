export function getErrorsForMachineId(machineId: string): ScenarioRecord[] {
  // Map machine to its corresponding errors
  if (machineId === "M-101") {
    return AUTHORITATIVE_SCENARIOS.filter((s) => s.error_id.startsWith("M1-"));
  }
  if (machineId === "M-201" || machineId === "M-202") {
    const machine = FACTORY_MACHINES.find((m) => m.machine_id === machineId);
    return AUTHORITATIVE_SCENARIOS.filter((s) => s.error_id.startsWith("M2-")).map((s) => ({
      ...s,
      machine_id: machineId,
      machine_name: machine?.machine_name || s.machine_name,
      operator: machine?.operator || s.operator,
    }));
  }
  if (["M-301", "M-302", "M-303", "M-304"].includes(machineId)) {
    const machine = FACTORY_MACHINES.find((m) => m.machine_id === machineId);
    return AUTHORITATIVE_SCENARIOS.filter((s) => s.error_id.startsWith("M3-")).map((s) => ({
      ...s,
      machine_id: machineId,
      machine_name: machine?.machine_name || s.machine_name,
      operator: machine?.operator || s.operator,
    }));
  }
  return [];
}
